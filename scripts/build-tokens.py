"""Build styles/tokens.css from tokens.json with Python's standard library.

Run from any directory: python scripts/build-tokens.py (from the repo root).
Schema 1.x is additive: existing flat token keys remain concrete JSON values.
semanticAliases maps color keys to other color keys; concrete compatibility
mirrors must agree in every complete theme, or the build fails before writing.
Camel-case color keys become --sf-kebab-case. Component radii and motion keys
become --sf-radius-*, --sf-duration-* and --sf-ease-* respectively. Existing
layout/font/shape aliases keep their established names. Tracking and columns
are additional exports, not changes to component styles.

Font paths are relative to the output stylesheet. No assets are written.
"""

from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tokens.json"
OUTPUT = ROOT / "styles" / "tokens.css"


def kebab(key):
    """Convert additive camel-case keys without renaming legacy CSS aliases."""
    if not re.fullmatch(r"[a-z][A-Za-z0-9]*", key):
        raise ValueError(f"Invalid token name: {key!r}")
    return re.sub(r"([A-Z])", r"-\1", key).lower()


def css_value(value):
    text = str(value)
    if not text or any(char in text for char in ";{}\n\r"):
        raise ValueError(f"Invalid CSS token value: {value!r}")
    return text


def font_stack(families):
    return ", ".join(json.dumps(name) if " " in name or "-Regular" in name
                     else name for name in families)


def color_lines(palette, aliases, roles):
    lines = []
    for key, value in palette.items():
        if key == "violet":
            comment = roles[key]
            if "*/" in comment or "\n" in comment:
                raise ValueError("Invalid violet role comment")
            lines.append(f"  /* {comment} */")
        target = aliases.get(key)
        rendered = f"var(--sf-{kebab(target)})" if target else css_value(value)
        lines.append(f"  --sf-{kebab(key)}: {rendered};")
    return lines


def validate(tokens):
    if not re.fullmatch(r"1\.\d+\.\d+", tokens["schemaVersion"]):
        raise ValueError("Unsupported schemaVersion (expected 1.x.y)")
    colors = tokens["color"]
    palettes = {"default": colors, **tokens["themes"]}
    if set(tokens["colorSchemes"]) != set(palettes):
        raise ValueError("colorSchemes must match default and all themes")
    for name, palette in palettes.items():
        kebab(name)
        if set(palette) != set(colors):
            raise ValueError(f"Theme {name!r} must export the complete color palette")
        if tokens["colorSchemes"][name] not in {"light", "dark"}:
            raise ValueError(f"Invalid color scheme for {name!r}")
        for alias, target in tokens["semanticAliases"].items():
            if alias not in palette or target not in palette:
                raise ValueError(f"Unknown semantic alias: {alias!r} -> {target!r}")
            if palette[alias] != palette[target]:
                raise ValueError(f"{name}.{alias} must mirror {name}.{target}")
            visited = {alias}
            while target in tokens["semanticAliases"]:
                if target in visited:
                    raise ValueError(f"Cyclic semantic alias: {alias!r}")
                visited.add(target)
                target = tokens["semanticAliases"][target]
    typography = tokens["typography"]
    faces = typography["fontFaces"]
    if [face["weight"] for face in faces] != typography["weights"]:
        raise ValueError("fontFaces must match the declared native weights in order")
    if not re.fullmatch(r"\d+\.\d+", typography["fontVersion"]):
        raise ValueError("fontVersion must be a quoted version string")
    for face in faces:
        if not (OUTPUT.parent / face["src"]).resolve().is_file():
            raise ValueError(f"Missing font source: {face['src']}")
    motion = tokens["motion"]
    durations = {"fast", "base", "slow"} | {
        f"componentDurations.{key}" for key in motion["componentDurations"]
    }
    if set(motion["reducedMotionOverrides"]) != durations:
        raise ValueError("reducedMotionOverrides must cover every duration exactly")


def render(tokens):
    validate(tokens)
    type_tokens = tokens["typography"]
    lines = ["/* Generated from tokens.json. Edit the JSON, then run",
             "   python scripts/build-tokens.py. Do not edit this file. */", ""]
    for face in type_tokens["fontFaces"]:
        url = f"{face['src']}?v={type_tokens['fontVersion']}"
        lines.extend([
            "@font-face {",
            f"  font-family: {json.dumps(type_tokens['family'])};",
            f"  src: url({json.dumps(url)}) format({json.dumps(face['format'])});",
            f"  font-style: {css_value(type_tokens['fontStyle'])};",
            f"  font-weight: {css_value(face['weight'])};",
            f"  font-display: {css_value(type_tokens['fontDisplay'])};",
            "}", "",
        ])
    lines.extend([":root {", f"  color-scheme: {tokens['colorSchemes']['default']};"])
    lines.extend(color_lines(tokens["color"], tokens["semanticAliases"], tokens["colorRoles"]))
    variables = {
        "font": f"{json.dumps(type_tokens['family'])}, {font_stack(type_tokens['fallbacks'])}",
        "mono": font_stack(type_tokens["monoFamily"]),
        "gutter": tokens["layout"]["gutter"],
        "max": tokens["layout"]["maxWidth"],
        "unit": tokens["layout"]["unit"],
        "section": tokens["layout"]["section"],
        "columns": tokens["layout"]["columns"],
        "radius-control": re.sub(r"^0\.", ".", tokens["shape"]["controlRadius"]),
        "radius-panel": tokens["shape"]["panelRadius"],
    }
    variables.update({f"tracking-{key.split('.', 1)[1]}": value
                      for key, value in type_tokens.items() if key.startswith("tracking.")})
    variables.update({f"radius-{kebab(key)}": value
                      for key, value in tokens["shape"]["componentRadii"].items()})
    motion = tokens["motion"]
    variables.update({key: motion[key] for key in ("ease", "fast", "base", "slow")})
    variables.update({f"duration-{kebab(key)}": value
                      for key, value in motion["componentDurations"].items()})
    variables.update({f"ease-{kebab(key)}": value
                      for key, value in motion["componentEasings"].items()})
    lines.extend(f"  --sf-{key}: {css_value(value)};" for key, value in variables.items())
    lines.extend(["}", ""])
    for name, palette in tokens["themes"].items():
        lines.extend([f'[data-mode="{name}"] {{',
                      f"  color-scheme: {tokens['colorSchemes'][name]};"])
        lines.extend(color_lines(palette, tokens["semanticAliases"], tokens["colorRoles"]))
        lines.extend(["}", ""])
    lines.extend(["@media (prefers-reduced-motion: reduce) {", "  :root {"])
    for path, value in motion["reducedMotionOverrides"].items():
        name = (f"duration-{kebab(path.split('.', 1)[1])}"
                if path.startswith("componentDurations.") else path)
        lines.append(f"    --sf-{name}: {css_value(value)};")
    lines.extend(["  }", "}", ""])
    return "\n".join(lines)


def main():
    try:
        tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
        stylesheet = render(tokens)
        OUTPUT.write_text(stylesheet, encoding="utf-8", newline="\n")
    except (OSError, KeyError, TypeError, ValueError) as error:
        raise SystemExit(f"Token build failed: {error}") from error
    print(f"Built {OUTPUT.relative_to(ROOT).as_posix()} from tokens.json "
          f"(schema {tokens['schemaVersion']}; {len(tokens['color'])} colors; "
          f"{len(tokens['themes'])} complete theme; "
          f"{len(tokens['typography']['fontFaces'])} native font faces)")


if __name__ == "__main__":
    main()
